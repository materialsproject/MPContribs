"""Searchable data for one CoRE MOF structure.

Data describes the nested scientific summaries of Contribution.data.
The models validate field values and their relationships. GeometryData
computes VPOV and GPOV from volume fractions and density. Structures and
the Zeo, topology, and RAC Tables are separate native components.
"""

from enum import StrEnum
from math import isfinite
from typing import Any, Literal

from pydantic import (
    BaseModel,
    ConfigDict,
    Field,
    NonNegativeFloat,
    NonNegativeInt,
    PositiveFloat,
    PositiveInt,
    computed_field,
    field_validator,
    model_validator,
)
from numpy import bool_ as NumpyBool
from pymatgen.core import Element


def reject_boolean_number(value: Any) -> Any:
    """Reject boolean scalars without disabling ordinary numeric coercion."""
    if isinstance(value, (bool, NumpyBool)):
        raise ValueError("A boolean is not a scientific count or magnitude")
    return value


class ReleaseData(BaseModel):
    """Dataset version information."""

    model_config = ConfigDict(extra="forbid", allow_inf_nan=False)

    releaseVersion: str = Field(min_length=1, description="CoRE dataset version.")


class SourceData(BaseModel):
    """Original source record and structure representation."""

    model_config = ConfigDict(extra="forbid", allow_inf_nan=False)

    sourceDatabase: Literal["COD", "CSD", "SI"] = Field(
        description="Source database category."
    )
    sourceId: str = Field(
        min_length=1, max_length=64, description="Identifier in the original source."
    )
    ccdcUrl: str | None = Field(
        default=None,
        pattern=r"^https?://[^/\s?#]+(?:[/?#][^\s]*)?$",
        description="Verified CCDC record URL; absent when unverified.",
    )
    structureVariant: Literal["ASR", "FSR", "ION"] = Field(
        description="Structure variant."
    )


class ReferenceData(BaseModel):
    """Reported structure name and publication reference."""

    model_config = ConfigDict(extra="forbid", allow_inf_nan=False)

    commonName: str | None = Field(
        default=None, max_length=512, description="Reported structure name."
    )
    doi: str | None = Field(
        default=None, max_length=128, description="Reported publication DOI."
    )
    publicationYear: int | None = Field(
        default=None, ge=1000, le=9999, description="Publication year."
    )

    validate_numeric_inputs = field_validator(
        "publicationYear",
        mode="before",
    )(reject_boolean_number)


class MofidData(BaseModel):
    """Versioned MOF identifiers; both versions may coexist for the same MOF.

    These do not replace the native identifier. Patterns validate the outer
    format, not the chemical validity of the encoded components.
    """

    model_config = ConfigDict(extra="forbid", allow_inf_nan=False)

    mofidV1: str | None = Field(
        default=None,
        pattern=(
            r"^[^\s;]+ MOFid-v1\.[^.\s;]+\.cat[0-9]+" r"(?:\.[^.\s;]+)?(?:;[^\r\n]*)?$"
        ),
        description=(
            "MOFid v1 using SMILES node/linker representations. Format: "
            "<components> MOFid-v1.<topology>.cat<n>, with optional "
            ".<revision> and ;<name> suffixes."
        ),
    )
    mofidV2: str | None = Field(
        default=None,
        pattern=(
            r"^[^\s;]+ MOFid-v2\.[^.\s;]+\.cat[0-9]+" r"(?:\.[^.\s;]+)?(?:;[^\r\n]*)?$"
        ),
        description=(
            "MOFid v2 generated by postprocessing MOFid v1 calculation outputs, "
            "using metal-node categories and SELFIES linkers. Format: "
            "<components> MOFid-v2.<topology>.cat<n>, with optional "
            ".<revision> and ;<name> suffixes."
        ),
    )


class CrystallographyData(BaseModel):
    """Metadata summaries for searching; the native Structure is separate."""

    model_config = ConfigDict(extra="forbid", allow_inf_nan=False)

    nAtoms: PositiveInt | None = Field(
        default=None, description="Atom count reported in metadata."
    )
    spaceGroupNumber: int | None = Field(
        default=None, ge=1, le=230, description="Metadata space-group number."
    )

    validate_numeric_inputs = field_validator(
        "nAtoms",
        "spaceGroupNumber",
        mode="before",
    )(reject_boolean_number)


class MetalData(BaseModel):
    """Metal and metalloid annotations."""

    model_config = ConfigDict(extra="forbid", allow_inf_nan=False)

    metalElements: str | None = Field(
        default=None,
        description=(
            "Semicolon-separated element symbols, each classified as a metal "
            "by pymatgen."
        ),
    )
    metalElementCount: NonNegativeInt = Field(
        description="Number of distinct metal elements."
    )
    metalAtomCount: NonNegativeInt = Field(
        description="Number of metal atoms; must be a nonnegative integer."
    )
    metalClasses: str | None = Field(
        default=None, description="Original metal classifications."
    )
    metalloidElements: str | None = Field(
        default=None, description="Semicolon-separated metalloid symbols."
    )

    @field_validator("metalElements")
    @classmethod
    def validate_metal_elements(cls, value: str | None) -> str | None:
        if value is None:
            return None
        for symbol in value.split(";"):
            try:
                element = Element(symbol)
            except ValueError as exc:
                raise ValueError(f"Invalid element symbol: {symbol!r}") from exc
            if not element.is_metal:
                raise ValueError(f"Element {symbol!r} is not classified as a metal")
        return value

    validate_numeric_inputs = field_validator(
        "metalElementCount",
        "metalAtomCount",
        mode="before",
    )(reject_boolean_number)


class CheckerStatus(StrEnum):
    """Completed scientific checker result."""

    PASS = "PASS"
    FAIL = "FAIL"


class ConsensusStatus(StrEnum):
    """Agreement within the named checker subset."""

    CR = "CR"
    NCR = "NCR"
    AMBIGUOUS = "AMBIGUOUS"


class CheckerData(BaseModel):
    """Completed scientific votes, with execution checked upstream.

    Within each named checker subset, all PASS means CR, all FAIL means
    NCR, and mixed PASS/FAIL means AMBIGUOUS. This model validates these
    relationships after validating the individual labels.
    """

    model_config = ConfigDict(extra="forbid", allow_inf_nan=False, use_enum_values=True)

    mofClassifierStatus: CheckerStatus = Field(
        description="Completed MOFClassifier vote."
    )
    mofCheckerStatus: CheckerStatus = Field(description="Completed MOFChecker vote.")
    chenManzStatus: CheckerStatus = Field(description="Completed Chen-Manz vote.")
    mosaecStatus: CheckerStatus = Field(description="Completed MOSAEC vote.")
    setcGatStatus: CheckerStatus = Field(description="Completed SETC-GAT vote.")
    consensus3: ConsensusStatus = Field(
        description="Recorded agreement of MOFClassifier, MOFChecker, and Chen-Manz."
    )
    consensus4: ConsensusStatus = Field(
        description=(
            "Recorded agreement of MOFClassifier, MOFChecker, Chen-Manz, and MOSAEC."
        )
    )
    consensus5: ConsensusStatus = Field(
        description="Recorded agreement of all five checkers."
    )

    @model_validator(mode="after")
    def validate_consensus(self) -> "CheckerData":
        votes = (
            self.mofClassifierStatus,
            self.mofCheckerStatus,
            self.chenManzStatus,
            self.mosaecStatus,
            self.setcGatStatus,
        )

        for count in (3, 4, 5):
            observed = set(votes[:count])

            if observed == {CheckerStatus.PASS}:
                expected = ConsensusStatus.CR
            elif observed == {CheckerStatus.FAIL}:
                expected = ConsensusStatus.NCR
            else:
                expected = ConsensusStatus.AMBIGUOUS

            field = f"consensus{count}"
            if getattr(self, field) != expected:
                raise ValueError(
                    f"{field} must be {expected.value} "
                    f"for the recorded checker votes"
                )

        return self


class TopologyData(BaseModel):
    """Availability and summaries of a selected parent topology result."""

    model_config = ConfigDict(extra="forbid", allow_inf_nan=False)

    topologyAvailable: bool = Field(
        description="Verified availability of final topology results."
    )
    networkDimension: int | None = Field(
        default=None,
        ge=0,
        le=3,
        description="Common subnet network dimension, or null when subnet dimensions differ.",
    )
    singleNodeNet: str | None = Field(
        default=None,
        description="Common SingleNodes topology key, or null when subnet keys differ.",
    )
    allNodeNet: str | None = Field(
        default=None,
        description="Common AllNodes topology key, or null when subnet keys differ.",
    )
    singleAllAgree: bool | None = Field(
        default=None,
        description="True when SingleNodes and AllNodes topology keys agree in every subnet.",
    )
    catenationDegree: PositiveInt | None = Field(
        default=None, description="Number of topology subnets."
    )

    @model_validator(mode="after")
    def validate_topology_summary(self) -> "TopologyData":
        summary_fields = {
            "networkDimension",
            "singleNodeNet",
            "allNodeNet",
            "singleAllAgree",
            "catenationDegree",
        }
        if self.topologyAvailable:
            missing = summary_fields - self.model_fields_set
            if missing:
                raise ValueError(
                    "Available topology requires explicit summary fields: "
                    + ", ".join(sorted(missing))
                )
            if self.singleAllAgree is None or self.catenationDegree is None:
                raise ValueError(
                    "Available topology requires singleAllAgree and catenationDegree"
                )
        elif any(getattr(self, name) is not None for name in summary_fields):
            raise ValueError("Unavailable topology must not contain summary values")
        return self

    validate_numeric_inputs = field_validator(
        "networkDimension",
        "catenationDegree",
        mode="before",
    )(reject_boolean_number)


class GeometryData(BaseModel):
    """Geometric descriptors corresponding to MOFSimplify, with camelCase API names.

    Twelve inputs copy the corresponding Zeo Table cells, including density;
    cellV copies metadata. vpov and gpov are read-only computed output fields.
    The fourteen MOFSimplify descriptor definitions are retained, with density
    as an additional calculation input. Probe settings determine the values.
    """

    model_config = ConfigDict(extra="forbid", allow_inf_nan=False)

    di: NonNegativeFloat | None = Field(
        default=None,
        description="MOFSimplify Di: maximum included-sphere diameter, angstrom.",
    )
    df: NonNegativeFloat | None = Field(
        default=None,
        description="MOFSimplify Df: maximum free-sphere diameter, angstrom.",
    )
    dif: float | None = Field(
        default=None,
        description=(
            "MOFSimplify Dif: maximum included-sphere diameter along the "
            "free-sphere path, angstrom; source sign policy is handled upstream."
        ),
    )
    density: PositiveFloat | None = Field(
        default=None,
        description="Structure density used in the MOFSimplify GPOV calculation, g/cm^3.",
    )
    gsa: NonNegativeFloat | None = Field(
        default=None,
        description="MOFSimplify GSA: gravimetric accessible surface area, m^2/g.",
    )
    vsa: NonNegativeFloat | None = Field(
        default=None,
        description="MOFSimplify VSA: volumetric accessible surface area, m^2/cm^3.",
    )
    cellV: PositiveFloat | None = Field(
        default=None,
        description="MOFSimplify cell_v: metadata unit-cell volume, angstrom^3.",
    )
    gpoav: NonNegativeFloat | None = Field(
        default=None,
        description="MOFSimplify GPOAV: gravimetric probe-accessible volume, cm^3/g.",
    )
    gponav: NonNegativeFloat | None = Field(
        default=None,
        description="MOFSimplify GPONAV: gravimetric probe-nonaccessible volume, cm^3/g.",
    )
    poav: NonNegativeFloat | None = Field(
        default=None,
        description="MOFSimplify POAV: probe-accessible volume per cell, angstrom^3.",
    )
    ponav: NonNegativeFloat | None = Field(
        default=None,
        description="MOFSimplify PONAV: probe-nonaccessible volume per cell, angstrom^3.",
    )
    poavVolFrac: float | None = Field(
        default=None,
        ge=0,
        le=1,
        description="MOFSimplify POAV_vol_frac: probe-accessible volume fraction.",
    )
    ponavVolFrac: float | None = Field(
        default=None,
        ge=0,
        le=1,
        description="MOFSimplify PONAV_vol_frac: probe-nonaccessible volume fraction.",
    )

    @computed_field(
        description="MOFSimplify VPOV: total probe-occupiable volume fraction, dimensionless.",
        json_schema_extra={"minimum": 0, "maximum": 1},
    )
    @property
    def vpov(self) -> float | None:
        if self.poavVolFrac is None or self.ponavVolFrac is None:
            return None
        return self.poavVolFrac + self.ponavVolFrac

    @computed_field(
        description="MOFSimplify GPOV: gravimetric total probe-occupiable volume, cm^3/g.",
        json_schema_extra={"minimum": 0},
    )
    @property
    def gpov(self) -> float | None:
        if self.vpov is None or self.density is None:
            return None
        return self.vpov / self.density

    @model_validator(mode="after")
    def validate_computed_volumes(self) -> "GeometryData":
        if self.vpov is not None and not 0 <= self.vpov <= 1:
            raise ValueError("poavVolFrac plus ponavVolFrac must be between 0 and 1")
        if self.gpov is not None and not isfinite(self.gpov):
            raise ValueError("Computed gpov must be finite")
        return self

    validate_numeric_inputs = field_validator(
        "di",
        "df",
        "dif",
        "density",
        "gsa",
        "vsa",
        "cellV",
        "gpoav",
        "gponav",
        "poav",
        "ponav",
        "poavVolFrac",
        "ponavVolFrac",
        mode="before",
    )(reject_boolean_number)


class Data(BaseModel):
    """Nested scientific summaries for one CoRE MOF Contribution.

    Five required groups contain fifteen required input fields. Four optional
    groups default to None. Geometry adds two computed output fields, and
    available topology requires explicit summary inputs. The native identifier,
    formula, structures, and Tables are separate Contribution components.
    """

    model_config = ConfigDict(extra="forbid", allow_inf_nan=False)

    release: ReleaseData
    source: SourceData
    reference: ReferenceData | None = None
    mofid: MofidData | None = None
    crystallography: CrystallographyData | None = None
    metal: MetalData
    checker: CheckerData
    topology: TopologyData
    geometry: GeometryData | None = None
